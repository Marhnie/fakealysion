// Deck analysis tools. Run from repo root: node scripts/test-decktools.mjs < /dev/null
import fs from 'node:fs';
import assert from 'node:assert/strict';
global.fetch = async (url) => ({ json: async () => JSON.parse(fs.readFileSync(url, 'utf8')) });
process.chdir(decodeURIComponent(new URL('..', import.meta.url).pathname).slice(1));
import * as S from '../src/state.js';
import * as E from '../src/engine.js';
import * as T from '../src/decktools.js';
import { parseDeckText } from '../src/deckimport.js';
await S.loadData();
const env = T.makeEnv(S, E);
let n = 0;
const ok = (c, m) => { n++; assert.ok(c, m); };
const near = (a, b, e, m) => { n++; assert.ok(Math.abs(a - b) <= e, `${m}: ${a} vs ${b}`); };
// ---- hypergeometric exactness
near(T.comb(50, 5), 2118760, 0.5, 'C(50,5)');
near(T.comb(5, 6), 0, 0, 'C(5,6)');
near(T.hyperAtLeast(50, 4, 5, 1), 1 - (46 * 45 * 44 * 43 * 42) / (50 * 49 * 48 * 47 * 46), 1e-12, '4 copies in 5');
near(T.hyperAtLeast(50, 1, 5, 1), 0.1, 1e-12, '1 copy in 5 = 10%');
near(T.hyperAtLeast(50, 1, 8, 1), 8 / 50, 1e-12, '1 copy in 8');
near([0, 1, 2, 3, 4].reduce((a, k) => a + T.hyperPmf(50, 4, 5, k), 0), 1, 1e-12, 'pmf sums to 1');
near(T.hyperAtLeast(10, 10, 5, 5), 1, 1e-12, 'all hits');
near(T.pSeeCard(0, 5), 0, 0, 'no copies');
near(T.pSeeCard(4, 8), 1 - T.comb(46, 8) / T.comb(50, 8), 1e-12, 'pSeeCard');
// ---- deck fixture
const r = parseDeckText(`4 EX1-066\n1 BT7-107\n2 BT8-084\n3 LM-032\n4 BT20-063\n4 BT20-068\n4 BT20-072\n2 BT20-088\n4 BT21-065\n4 BT23-064\n3 BT23-087\n4 BT23-069\n3 BT23-098\n2 BT23-065\n3 BT23-061\n3 BT23-071\n4 BT20-006`, S);
const deck = { main: r.main, digitama: r.digitama, art: {} };
const st = T.deckStats(deck, env);
ok(st.mainN === T.sumCounts(deck.main), 'mainN');
ok(st.digN === T.sumCounts(deck.digitama), 'digN');
ok(st.cat.digimon + st.cat.tamer + st.cat.option === st.mainN, 'categories partition main');
ok(Object.values(st.lv).reduce((a, b) => a + b, 0) === st.cat.digimon, 'Lv histogram = digimon');
ok(['digimon', 'tamer', 'option'].reduce((a, k) => a + st.curve[k].reduce((x, y) => x + y, 0), 0) === st.costN, 'curve total');
ok(st.dp.reduce((a, b) => a + b.n, 0) === st.cat.digimon, 'DP buckets = digimon');
ok(st.avgCost > 0 && st.avgCost < 15, 'avg cost sane');
ok(st.four.every(id => (deck.main[id] || deck.digitama[id]) >= 4), '4-copy list');
ok(Object.values(st.colors).every(v => v > 0), 'colors');
ok(st.securityDensity >= 0 && st.securityDensity <= 1, 'security density');
ok(Array.isArray(st.topTraits), 'traits');
ok(st.parN === 0, 'no parallels');
ok(T.deckStats({ ...deck, art: { 'EX1-066': 'EX1-066_P1' } }, env, { evo: false }).parN === 1, 'parallel count');
// ---- evolution graph on a tiny hand-made deck
const lv2 = Object.values(S.CARDS).find(c => c.category === 'digitama' && c.colors.length === 1);
const lv3 = Object.values(S.CARDS).find(c => c.category === 'digimon' && c.level === 3 && c.evoNormal && c.evoNormal.level === 2 && c.colors[0] === lv2.colors[0]);
const lv5 = Object.values(S.CARDS).find(c => c.category === 'digimon' && c.level === 5 && c.evoNormal && c.evoNormal.level === 4 && c.colors[0] === lv2.colors[0] && !/조그레스|버스트|어플/.test(c.effectKo || ''));
const tiny = { main: { [lv3.id]: 4, [lv5.id]: 2 }, digitama: { [lv2.id]: 4 } };
const g = T.evoGraph(tiny, env);
ok(g.sources[lv3.id].includes(lv2.id) === env.canEvolve(lv2.id, lv3.id), 'graph agrees with canEvolve');
ok(g.orphans.includes(lv5.id), 'Lv5 without Lv4 is an orphan');
ok(!g.orphans.includes(lv3.id), 'Lv3 not orphan');
ok(g.reach.has(lv3.id) && g.reach.has(lv2.id), 'reach starters');
const lv4 = Object.values(S.CARDS).find(c => c.category === 'digimon' && c.level === 4 && env.canEvolve(lv3.id, c.id) && env.canEvolve(c.id, lv5.id));
if (lv4) { const g2 = T.evoGraph({ main: { ...tiny.main, [lv4.id]: 2 }, digitama: tiny.digitama }, env); ok(!g2.orphans.includes(lv5.id) && g2.sources[lv5.id].includes(lv4.id), 'chain makes Lv5 reachable'); } else ok(true, 'no lv4 chain in data');
// ---- checkup
const cu = T.deckCheckup(tiny, env);
ok(cu.some(x => x.code === 'legal' && x.level === 'error'), 'illegal 50-card count flagged');
ok(cu.some(x => x.code === 'orphan' && x.ids.includes(lv5.id)), 'orphan flagged with ids');
ok(cu.every(x => x.why && x.title), 'all issues explained');
ok(cu[0].level === 'error', 'errors sorted first');
const opt = Object.values(S.CARDS).find(c => c.category === 'option' && c.colors.length === 1 && !c.colors.includes(lv2.colors[0]));
ok(T.deckCheckup({ main: { ...tiny.main, [opt.id]: 2 }, digitama: tiny.digitama }, env).some(x => x.code === 'option-color' && x.ids.includes(opt.id)), 'option color condition (4-22)');
ok(T.deckCheckup({ main: { [lv3.id]: 4 }, digitama: {} }, env).some(x => x.code === 'no-digitama'), 'no digitama');
// ---- simulation
const model = T.buildSimModel(deck, env);
ok(model.ids.length === st.mainN, 'model size');
ok(T.mulberry32(42)() === T.mulberry32(42)(), 'seeded rng deterministic');
const tid = Object.keys(deck.main)[0], tc = deck.main[tid];
const res = T.runBatchSync(deck, env, { n: 20000, rng: T.mulberry32(7), targetId: tid });
ok(res.n === 20000, 'ran all hands');
for (const k of ['pLv3', 'pLv2', 'pNoLow', 'pBlocker', 'pLine', 'pLineEgg', 'pGood', 'pGoodAfterMulligan']) ok(res[k] >= 0 && res[k] <= 1, k + ' in [0,1]');
ok(res.pGoodAfterMulligan >= res.pGood, 'mulligan never hurts');
near(res.pLv3, T.hyperAtLeast(st.mainN, st.lv[3], 5, 1), 0.012, 'sim P(>=1 Lv3) ~ exact');
const blk = model.flags.filter(f => f.blocker).length;
near(res.pBlocker, T.hyperAtLeast(st.mainN, blk, 5, 1), 0.012, 'sim P(blocker) ~ exact');
near(res.pTargetOpen, T.pSeeCard(tc, 5, st.mainN), 0.012, 'sim P(card in opening) ~ exact');
near(res.pTargetTurns, T.pSeeCard(tc, 8, st.mainN), 0.012, 'sim P(card in 8) ~ exact');
near(res.avgTamers, 5 * model.flags.filter(f => f.tamer).length / st.mainN, 0.03, 'avg tamers = 5*K/N');
const b = T.createBatch(deck, env, { n: 1000, rng: T.mulberry32(1) });
let steps = 0; while (!b.step(300)) steps++;
ok(steps === 3 && b.result().n === 1000, 'chunked stepping');
ok(JSON.stringify(T.runBatchSync(deck, env, { n: 500, rng: T.mulberry32(3) })) === JSON.stringify(T.runBatchSync(deck, env, { n: 500, rng: T.mulberry32(3) })), 'batch deterministic');
ok(T.runBatchSync({ main: { [lv3.id]: 4 }, digitama: {} }, env, { n: 200 }).n === 200, 'tiny deck handled');
// ---- sample hand
const s = T.sampleNew(deck, T.mulberry32(5));
ok(s.hand.length === 5 && s.deck.length === st.mainN - 5, 'opening 5');
ok(T.sampleMulligan(s) && s.hand.length === 5 && s.deck.length === st.mainN - 5, 'mulligan keeps 5');
ok(!T.sampleMulligan(s), 'only one mulligan');
T.sampleKeep(s); ok(s.security.length === 5 && s.deck.length === st.mainN - 10, 'security 5');
const d0 = s.deck.length; T.sampleDraw(s); ok(s.hand.length === 6 && s.deck.length === d0 - 1, 'draw 1');
ok(s.digitama.length === st.digN, 'digitama separate'); ok(T.sampleHatch(s) && s.digitama.length === st.digN - 1, 'hatch');
ok([...s.hand, ...s.deck, ...s.security].sort().join() === T.expand(deck.main).sort().join(), 'no cards lost');
// ---- diff / sort / management
const dA = { main: { a: 2, b: 1 }, digitama: { e: 4 } }, dB = { main: { a: 4, c: 3 }, digitama: {} };
const df = T.diffDecks(dA, dB);
ok(df.added === 5 && df.removed === 5 && df.same === 2, 'diff totals');
ok(df.rows.length === 4, 'diff rows');
const se = T.sortEntries(Object.entries(deck.main), 'lv', S.card);
ok(se.length === Object.keys(deck.main).length && (S.card(se[0][0]).level ?? 99) <= (S.card(se[se.length - 1][0]).level ?? 99), 'sort by lv');
ok(T.sortEntries([['x', 1]], 'none', S.card).length === 1, 'sort none');
const ds = { A: { name: 'A', main: {}, digitama: {} }, B: { name: 'B', main: {}, digitama: {} }, C: { name: 'C', main: {}, digitama: {} } };
ok(Object.keys(T.renameDeck(ds, 'B', 'Z')).join() === 'A,Z,C', 'rename keeps order');
ok(T.renameDeck(ds, 'B', 'A') === null, 'rename collision');
ok(Object.keys(T.moveDeck(ds, 'C', -1)).join() === 'A,C,B', 'move up');
ok(T.moveDeck(ds, 'A', -1) === null, 'move out of range');
const dup = T.duplicateDeck(ds, 'A');
ok(Object.keys(dup.decks).join() === 'A,A (복사),B,C', 'duplicate placed next');
ok(T.duplicateDeck(dup.decks, 'A').name === 'A (복사 2)', 'unique dup name');
const dr = { main: {}, digitama: {} };
ok(T.setCount(dr, 'EX1-066', 9, env) === env.maxCopies('EX1-066') && dr.main['EX1-066'] === 4, 'setCount clamps to copy limit');
ok(T.setCount(dr, 'EX1-066', 0, env) === 0 && !dr.main['EX1-066'], 'setCount 0 removes');
const bk = T.exportBackup({ X: { name: 'X', main: { 'EX1-066': 4 }, digitama: {}, art: {} } });
const pb = T.parseBackup(bk, env);
ok(pb.errors.length === 0 && pb.decks.X.main['EX1-066'] === 4, 'backup round trip');
ok(T.parseBackup('{oops', env).errors.length === 1, 'bad json');
ok(T.parseBackup(JSON.stringify({ Y: { main: { 'ZZ-999': 2 }, digitama: {} } }), env).errors.length === 1, 'unknown card dropped');
console.log(`decktools tests OK (${n} assertions)`);
